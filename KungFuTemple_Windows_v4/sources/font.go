var accents = map[rune]struct {
	base rune
	mark int // 0 aigu 1 grave 2 circonflexe 3 cédille 4 tréma
}{
	'É': {'E', 0}, 'È': {'E', 1}, 'Ê': {'E', 2}, 'Ë': {'E', 4}, 'À': {'A', 1}, 'Â': {'A', 2},
	'Î': {'I', 2}, 'Ï': {'I', 4}, 'Ô': {'O', 2}, 'Û': {'U', 2}, 'Ù': {'U', 1}, 'Ç': {'C', 3},
}

var markPix = [5][2]string{{"   # ", "  #  "}, {" #   ", "  #  "}, {"  #  ", " # # "}, {"  #  ", " #   "}, {" # # ", "     "}}

func textWidth(s string, sc int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return n*6*sc - sc
}

// Text dessine une chaîne ; align 0 gauche, 1 centre, 2 droite.
func (f *FB) Text(s string, x, y, sc int, c uint32, align int, shadow bool) {
	s = strings.ToUpper(s)
	w := textWidth(s, sc)
	if align == 1 {
		x -= w / 2
	} else if align == 2 {
		x -= w
	}
	if shadow {
		f.text(s, x+sc, y+sc, sc, 0x000000)
	}
	f.text(s, x, y, sc, c)
}

func (f *FB) text(s string, x, y, sc int, c uint32) {
	for _, r := range s {
		g, ok := glyphs[r]
		mark := -1
		if !ok {
			if a, ok2 := accents[r]; ok2 {
				g = glyphs[a.base]
				mark = a.mark
			} else {
				g = glyphs['?']
			}
		}
		for gy, line := range g {
			for gx, p := range line {
				if p == '#' {
					f.Rect(x+gx*sc, y+gy*sc, sc, sc, c)
				}
			}
		}
		if mark >= 0 {
			for i, line := range markPix[mark] {
				oy := y + (i-2)*sc
				if mark == 3 {
					oy = y + (7+i)*sc
				}
				for gx, p := range line {
					if p == '#' {
						f.Rect(x+gx*sc, oy, sc, sc, c)
					}
				}
			}
		}
		x += 6 * sc
	}
}
